/**
 * Event scene art — native 64×64. `.` transparent; palette keys — see palette.ts.
 */
import type { SpriteRows } from '../types'

export const EVENT_GRID_SIZE = 64

const W = EVENT_GRID_SIZE
const EMPTY = '.'.repeat(W)

/** 56-char drawable band inside tomb frame (`..23` + 56 + `32..`). */
function band(inner: string): string {
  return `..23${inner.slice(0, 56).padEnd(56, '.')}32..`
}

function frameTop(): string[] {
  return [
    EMPTY,
    EMPTY,
    '..222222222222222222222222222222222222222222222222222222222222..',
    '..233333333333333333333333333333333333333333333333333333333332..',
  ]
}

function frameBottom(): string[] {
  return [
    '..233333333333333333333333333333333333333333333333333333333332..',
    '..uuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuu..',
    '..uttttttttttttttttttttttttttttttttttttttttttttttttttttttttttu..',
    '..uuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuuu..',
  ]
}

function compose(content: string[]): SpriteRows {
  const rows = [...frameTop(), ...content.map(band), ...frameBottom()]
  while (rows.length < W) rows.push(EMPTY)
  if (rows.length > W) {
    throw new Error(`event art compose: ${rows.length} rows (max ${W})`)
  }
  return rows.map((row, i) => {
    const line = row.padEnd(W, '.').slice(0, W)
    if (line.length !== W) throw new Error(`event art row ${i}: width ${line.length}`)
    return line
  })
}

